"""
Textos (inglés y español) que la web muestra para cada video.

La página web solo sabe de reproducción, pistas y gráficas: todo lo que depende del video
(título, pie de foto, nombre de las pistas, qué es cada medida, qué hace cada medida en la
música, créditos) viaja en su manifiesto, en `texts.en` y `texts.es`. Este módulo lo arma a
partir de la ficha del video (videos/<id>.json), del analizador y de la música.

Lo que hace cada medida en la música sale de plantillas por papel (pad, voces, acentos,
bajo); la ficha puede reemplazar cualquiera en texts.<idioma>.effects.<pista>.<medida>.
"""
